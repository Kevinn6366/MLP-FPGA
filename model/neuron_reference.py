"""Integer oracle for the first neuron; no training or quantization yet."""
from pathlib import Path
import random

def reference(xs, ws, bias):
    assert len(xs) == len(ws) == 4
    assert all(-128 <= v <= 127 for v in xs + ws)
    assert -32768 <= bias <= 32767
    # Python integers are unbounded: no accidental RTL-width wraparound.
    trace = [bias]
    for x, w in zip(xs, ws):
        trace.append(trace[-1] + x * w)
    assert all(-(1 << 17) <= v < (1 << 17) for v in trace)
    return trace, max(0, trace[-1])

def pack(values):
    return sum((v & 255) << (8*i) for i, v in enumerate(values))

def main():
    cases = [
        ([1,2,3,4], [2,-1,1,0], 1),
        ([1,2,3,4], [-2,-1,-1,0], -1),
        ([0]*4, [127]*4, 0),
        ([-128]*4, [-128]*4, 32767),
        ([-128]*4, [127]*4, -32768),
        ([127]*4, [127]*4, 32767),
        ([0]*4, [-128]*4, 32767),
        ([0]*4, [127]*4, -32768),
        ([1,-1,1,-1], [127]*4, 0),
    ]
    rng = random.Random(20261010)
    for _ in range(32):
        cases.append(([rng.randint(-128,127) for _ in range(4)],
                      [rng.randint(-128,127) for _ in range(4)], rng.randint(-32768,32767)))
    lines = ['// Generated by model/neuron_reference.py; deterministic integer oracle.']
    for xs,ws,bias in cases:
        trace,y=reference(xs,ws,bias)
        lines.append(f"run_case(32'h{pack(xs):08x}, 32'h{pack(ws):08x}, 16'h{bias & 65535:04x}, "
                     + ', '.join(map(str, trace + [y])) + ');')
    path = Path(__file__).resolve().parents[1] / 'sim' / 'vectors.vh'
    path.write_text('\n'.join(lines)+'\n',encoding='ascii')
    print(f'Generated {len(cases)} cases; example trace={reference(*cases[0])[0]}, y=4')

if __name__ == '__main__':
    main()
